"""Correctness tests for survival model adapters against analytical ground truth
and R marginaleffects reference values.

These tests verify that pymargins produces mathematically correct point estimates
for survival model predictions and marginal effects.

Notes on scale differences
--------------------------
- R marginaleffects ``predictions(type='risk')`` for Cox PH returns *centered*
  relative risk: exp(Xβ - mean(Xβ)). Our PHReg adapter returns raw hazard
  ratios exp(Xβ). Our lifelines CoxPH adapter returns centered partial hazards
  exp((X - X_mean)β), matching marginaleffects.

- R marginaleffects ``predictions(type='response')`` for Weibull AFT (survreg)
  returns mean survival time. Our Weibull adapter predicts survival probability
  S(t|x) at a fixed time. These are different scales, so we compare against
  manually computed S(t|x) values.

Reference values
----------------
R marginaleffects reference values were generated by::

    Rscript tests/_generate_survival_reference.R

and are hard-coded below. The R script uses the survival and marginaleffects
packages with seed=42 and n=200.
"""

