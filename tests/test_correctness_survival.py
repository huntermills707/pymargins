def test_weibull_predictions_match_analytical(df_survival):
    """Survival probabilities should match analytical S(t|x) formula."""
    fit = WeibullAFTFitter()
    fit.fit(df_survival, duration_col="time", event_col="status")
    adapter = LifelinesWeibullAFTAdapter(fit, training_data=df_survival)

    t_med = adapter._prediction_time
    beta = fit.params_
    beta_lambda = beta.loc["lambda_"].values
    beta_rho = beta.loc["rho_"].values
    rho = np.exp(beta_rho[0])

    X5 = np.asarray(adapter.design_matrix_from_df(df_survival.head(5)))
    lambda_x = np.exp(X5 @ beta_lambda)
    manual_S = np.exp(-(t_med / lambda_x) ** rho)

    pred = np.asarray(adapter.predict(adapter.coefficients(), X5))

    np.testing.assert_allclose(pred, manual_S, rtol=1e-6)


def test_weibull_ame_matches_analytical(df_survival):
    """AME on survival probability scale should match analytical derivative."""
    fit = WeibullAFTFitter()
    fit.fit(df_survival, duration_col="time", event_col="status")
    adapter = LifelinesWeibullAFTAdapter(fit, training_data=df_survival)
    # Identity scale is appropriate for survival probabilities (bounded [0,1])
    m = Margins(fit, adapter=adapter)

    res_x1 = m.dydx("x1")
    res_x2 = m.dydx("x2")

    # Analytical derivative: dS/dx_j = S * rho * (t/lambda)^rho * beta_lambda_j
    t_med = adapter._prediction_time
    beta = fit.params_
    beta_lambda = beta.loc["lambda_"].values
    beta_rho = beta.loc["rho_"].values
    rho = np.exp(beta_rho[0])

    X_all = np.asarray(adapter.design_matrix_from_df(df_survival))
    lambda_all = np.exp(X_all @ beta_lambda)
    S_all = np.exp(-(t_med / lambda_all) ** rho)

    manual_ame_x1 = np.mean(S_all * rho * (t_med / lambda_all) ** rho * beta_lambda[0])
    manual_ame_x2 = np.mean(S_all * rho * (t_med / lambda_all) ** rho * beta_lambda[1])

    np.testing.assert_allclose(float(res_x1.estimate), manual_ame_x1, rtol=1e-4)
    np.testing.assert_allclose(float(res_x2.estimate), manual_ame_x2, rtol=1e-4)


