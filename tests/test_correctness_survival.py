def test_phreg_predictions_match_analytical(df_survival):
    """PHReg predict() should return raw exp(X @ beta)."""
    fit = PHReg(
        df_survival["time"].values,
        df_survival[["x1", "x2"]].values,
        status=df_survival["status"].values,
    ).fit()
    adapter = StatsmodelsPHRegAdapter(fit, training_data=df_survival)

    X5 = adapter.design_matrix_from_df(df_survival.head(5))
    pred = np.asarray(adapter.predict(adapter.coefficients(), X5))

    # Manual computation
    beta = fit.params
    X = df_survival[["x1", "x2"]].head(5).values
    manual = np.exp(X @ beta)

    np.testing.assert_allclose(pred, manual, rtol=1e-10)


def test_phreg_predictions_differ_from_centered_risk(df_survival):
    """Raw HR predictions differ from marginaleffects' centered risk by ~1%."""
    fit = PHReg(
        df_survival["time"].values,
        df_survival[["x1", "x2"]].values,
        status=df_survival["status"].values,
    ).fit()
    adapter = StatsmodelsPHRegAdapter(fit, training_data=df_survival)

    X5 = adapter.design_matrix_from_df(df_survival.head(5))
    pred = np.asarray(adapter.predict(adapter.coefficients(), X5))

    # R marginaleffects type='risk' is centered at the mean
    # The ratio should be roughly constant = exp(-mean(X @ beta))
    mean_lp = np.mean(df_survival[["x1", "x2"]].values @ fit.params)
    centered_manual = np.exp(df_survival[["x1", "x2"]].head(5).values @ fit.params - mean_lp)

    np.testing.assert_allclose(pred / centered_manual, np.exp(mean_lp), rtol=1e-10)


def test_phreg_ame_matches_analytical(df_survival):
    """AME on raw HR scale should match mean(beta * exp(X @ beta))."""
    fit = PHReg(
        df_survival["time"].values,
        df_survival[["x1", "x2"]].values,
        status=df_survival["status"].values,
    ).fit()
    adapter = StatsmodelsPHRegAdapter(fit, training_data=df_survival)
    # Use identity scale for dydx (marginal effects can be negative)
    m = Margins(fit, adapter=adapter)

    res_x1 = m.dydx("x1")
    res_x2 = m.dydx("x2")

    # Analytical ground truth
    X = df_survival[["x1", "x2"]].values
    pred_all = np.exp(X @ fit.params)
    manual_ame_x1 = np.mean(fit.params[0] * pred_all)
    manual_ame_x2 = np.mean(fit.params[1] * pred_all)

    np.testing.assert_allclose(float(res_x1.estimate), manual_ame_x1, rtol=1e-5)
    np.testing.assert_allclose(float(res_x2.estimate), manual_ame_x2, rtol=1e-5)


